import { HttpStatus, Injectable, Logger, OnModuleDestroy, OnModuleInit } from '@nestjs/common';
import type { Prisma, TicketMessage, User } from '@prisma/client';
import { detectLang, draftOutcome, maskSensitive } from '@tp/shared';
import { PrismaService } from '../../common/prisma.service';
import { AiService } from '../ai/ai.service';
import { DomainEvents } from '../../common/domain-events';
import { ClientGroupsService } from '../tickets/client-groups.service';
import { AppError } from '../../common/http';
import { KbSearchService, type KbHit, type TemplateHit } from './kb-search.service';

export const NOT_FOUND_MARKER = 'NOT_FOUND';

export interface DraftSource {
  type: 'article' | 'template';
  id: string;
  title: string;
  score: number;
}

export interface DraftResult {
  id: string;
  ticketId: string;
  ticketNumber: number;
  chatId: string;
  draft: string | null;
  /** Nothing relevant in the knowledge base: NO answer is invented, the human writes it. */
  notFound: boolean;
  /** llm = generated by the configured model from the retrieved material; extractive = composed from the best article (no AI). */
  mode: 'llm' | 'extractive' | 'none';
  sources: DraftSource[];
  /** What the AI provider saw instead of the raw customer text (secrets masked), so the UI can show a preview. */
  masked: { text: string; hits: number };
  maskPolicy: string;
  vectorUsed: boolean;
  warning?: string;
}

const MAX_AGE_MS = 30 * 60_000; // a draft is attributed to the next matching outgoing message within 30 minutes

const clip = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

/**
 * Reply drafts (RAG). Answers come ONLY from approved knowledge-base articles (and templates as phrasing material);
 * when nothing relevant is found the result is `notFound` and the model is never asked. Secrets are masked before any
 * text reaches an AI provider. The draft is stored so we can later tell whether it was sent unchanged or edited.
 */
@Injectable()
export class DraftService implements OnModuleInit, OnModuleDestroy {
  private readonly logger = new Logger('Draft');
  private offs: Array<() => void> = [];

  constructor(
    private readonly prisma: PrismaService,
    private readonly search: KbSearchService,
    private readonly ai: AiService,
    private readonly groups: ClientGroupsService,
    private readonly events: DomainEvents,
  ) {}

  onModuleInit() {
    this.offs = [
      // ".ai" typed by staff in a customer chat: generate and deliver the draft to the extension over the WebSocket
      this.events.on('ai.requested', async (p) => {
        try {
          const d = await this.generate({
            chatId: p.chatId,
            messageId: p.messageId ?? undefined,
            userId: p.actorId,
          });
          this.events.emit('draft.ready', {
            userId: p.actorId,
            draft: d as unknown as Record<string, unknown>,
          });
        } catch (e) {
          this.logger.warn(`.ai draft failed: ${String(e).slice(0, 200)}`);
        }
      }),
      this.events.on('ticket.message', (p) => {
        if (p.direction === 'OUT' && p.text && !p.isInternalNote) {
          void this.onOutgoing(p.ticketId, p.text, p.answeredById ?? null, p.sentAt ?? new Date()).catch(
            (e) => this.logger.warn(`draft outcome tracking failed: ${String(e).slice(0, 200)}`),
          );
        }
      }),
    ];
  }
  onModuleDestroy() {
    this.offs.forEach((o) => o());
  }

  // ------------------------------------------------------------------ generation

  async generate(req: { chatId: string; messageId?: string; userId: string | null }): Promise<DraftResult> {
    const group = await this.groups.findByAnyId(req.chatId);
    if (!group)
      throw new AppError(HttpStatus.NOT_FOUND, 'NOT_FOUND', 'Bu chat mijoz guruhi sifatida topilmadi');
    const ticket =
      (await this.prisma.ticket.findFirst({
        where: { clientGroupId: group.id, status: { not: 'CLOSED' } },
      })) ??
      (await this.prisma.ticket.findFirst({
        where: { clientGroupId: group.id },
        orderBy: { openedAt: 'desc' },
      }));
    if (!ticket)
      throw new AppError(HttpStatus.NOT_FOUND, 'NO_CONVERSATION', "Bu chat uchun saqlangan suhbat yo'q");

    const msgs = await this.prisma.ticketMessage.findMany({
      where: { ticketId: ticket.id, isInternalNote: false },
      orderBy: { sentAt: 'asc' },
    });
    const { target, warning: pickWarning } = this.pickTarget(msgs, req.messageId);
    if (!target.length)
      throw new AppError(HttpStatus.NOT_FOUND, 'NO_CUSTOMER_MESSAGE', 'Mijoz xabari topilmadi');

    const raw = target.map((m) => m.text).join('\n');
    const masked = maskSensitive(raw);
    const lang = detectLang(masked.text);
    const settings = await this.prisma.aiSettings.findUniqueOrThrow({ where: { id: 1 } });

    const found = await this.search.search(masked.text, { lang, systemType: group.systemType });
    const templates = await this.search.templates(masked.text);
    const user = req.userId ? await this.prisma.user.findUnique({ where: { id: req.userId } }) : null;

    const base = {
      ticketId: ticket.id,
      ticketNumber: ticket.number,
      chatId: group.telegramChatId,
      masked: { text: masked.text, hits: masked.hits.length },
      maskPolicy: settings.maskPolicy,
      vectorUsed: found.vectorUsed,
    };
    const save = async (r: Omit<DraftResult, 'id'>) => {
      const row = await this.prisma.aiDraft.create({
        data: {
          clientGroupId: group.id,
          ticketId: ticket.id,
          userId: req.userId,
          sourceMessageId: target[target.length - 1].telegramMessageId,
          text: r.draft,
          notFound: r.notFound,
          mode: r.mode === 'llm' ? 'llm' : 'extractive',
          sources: r.sources as unknown as Prisma.InputJsonValue,
        },
      });
      const arts = r.sources.filter((s) => s.type === 'article').map((s) => s.id);
      if (arts.length)
        await this.prisma.kbArticle.updateMany({
          where: { id: { in: arts } },
          data: { useCount: { increment: 1 } },
        });
      return { id: row.id, ...r };
    };

    if (!found.hits.length && !templates.length) {
      return save({ ...base, draft: null, notFound: true, mode: 'none', sources: [], warning: pickWarning });
    }
    const sources: DraftSource[] = [
      ...found.hits.map((h) => ({
        type: 'article' as const,
        id: h.article.id,
        title: h.article.problem,
        score: Math.round(h.score * 1000) / 1000,
      })),
      ...templates.map((t) => ({
        type: 'template' as const,
        id: t.template.id,
        title: t.template.title,
        score: Math.round(t.score * 100) / 100,
      })),
    ];

    let warning = pickWarning;
    if (await this.ai.isConfigured('draft')) {
      try {
        const text = await this.ai.complete({
          task: 'draft',
          user: this.llmPrompt(found.hits, templates, msgs, target, masked.text, lang, group.companyName),
          ticketId: ticket.id,
        });
        if (!text.trim() || text.includes(NOT_FOUND_MARKER)) {
          return save({ ...base, draft: null, notFound: true, mode: 'llm', sources: [], warning });
        }
        return save({ ...base, draft: text.trim(), notFound: false, mode: 'llm', sources, warning });
      } catch (e) {
        // budget / timeout / provider error: still useful to show the KB answer itself
        warning = `AI ishlamadi, bazadagi javob ko'rsatildi (${String(e).slice(0, 80)})`;
        this.logger.warn(`LLM draft failed, falling back to extractive: ${String(e).slice(0, 200)}`);
      }
    }
    const draft = this.extractive(found.hits, templates, lang, user);
    return save({
      ...base,
      draft,
      notFound: !draft,
      mode: draft ? 'extractive' : 'none',
      sources: draft ? sources : [],
      warning,
    });
  }

  /** Which customer message(s) to answer: the selected one (plus a little context) or everything since the last staff reply. */
  private pickTarget(
    msgs: TicketMessage[],
    messageId?: string,
  ): { target: TicketMessage[]; warning?: string } {
    const incoming = msgs.filter((m) => m.direction === 'IN');
    if (messageId && /^\d+$/.test(messageId)) {
      const i = msgs.findIndex((m) => m.telegramMessageId === BigInt(messageId));
      if (i >= 0 && msgs[i].direction === 'IN') return { target: [msgs[i]] };
      return {
        target: this.latestIncoming(msgs, incoming),
        warning: 'Tanlangan xabar topilmadi, oxirgi mijoz xabarlari ishlatildi',
      };
    }
    return { target: this.latestIncoming(msgs, incoming) };
  }

  private latestIncoming(msgs: TicketMessage[], incoming: TicketMessage[]): TicketMessage[] {
    const lastOut = [...msgs].reverse().find((m) => m.direction === 'OUT');
    const since = lastOut ? incoming.filter((m) => m.sentAt > lastOut.sentAt) : incoming;
    return (since.length ? since : incoming).slice(-5);
  }

  private llmPrompt(
    hits: KbHit[],
    templates: TemplateHit[],
    msgs: TicketMessage[],
    target: TicketMessage[],
    maskedQuestion: string,
    lang: string,
    company: string,
  ): string {
    const arts = hits
      .map(
        (h) =>
          `<article id="${h.article.id}" system="${h.article.systemType}" lang="${h.article.lang}">\nProblem: ${h.article.problem}\nSolution: ${h.article.solution}\n</article>`,
      )
      .join('\n');
    const tpls = templates
      .map(
        (t) =>
          `<template id="${t.template.id}" title="${t.template.title}">\n${t.template.bodyUz}\n</template>`,
      )
      .join('\n');
    const targetIds = new Set(target.map((m) => m.id));
    const convo = msgs
      .filter((m) => !targetIds.has(m.id))
      .slice(-6)
      .map((m) => `${m.direction === 'OUT' ? 'agent' : 'customer'}: ${clip(maskSensitive(m.text).text, 300)}`)
      .join('\n');
    return [
      `<articles>\n${arts || '(none)'}\n</articles>`,
      tpls ? `<templates>\n${tpls}\n</templates>` : '',
      convo ? `<conversation>\n${convo}\n</conversation>` : '',
      `<customer_question company="${company}">\n${maskedQuestion}\n</customer_question>`,
      `Customer language: ${lang}. Answer ONLY from the articles above. Write the draft reply for the human agent now, or ${NOT_FOUND_MARKER}.`,
    ]
      .filter(Boolean)
      .join('\n\n');
  }

  /** No-AI composition: the best article's solution (in the customer's language when possible), or the best template. */
  private extractive(
    hits: KbHit[],
    templates: TemplateHit[],
    lang: 'uz' | 'ru',
    user: User | null,
  ): string | null {
    const sign = user
      ? lang === 'ru'
        ? `\nС уважением, ${user.displayName}.`
        : `\nHurmat bilan, ${user.displayName}.`
      : '';
    const best = hits.find((h) => h.article.lang === lang) ?? hits[0];
    if (best)
      return `${lang === 'ru' ? 'По вашему вопросу: ' : "Murojaatingiz bo'yicha: "}${best.article.solution}${sign}`;
    const t = templates[0]?.template;
    if (t)
      return `${(lang === 'ru' && t.bodyRu ? t.bodyRu : t.bodyUz).replace(/\{xodim\}/g, user?.displayName ?? '{xodim}')}`;
    return null;
  }

  // ------------------------------------------------------------------ what did the human do with the draft?

  /**
   * When staff send a message in the ticket's chat shortly after a draft: identical => UNCHANGED, similar => EDITED,
   * unrelated => ignored (the draft stays unresolved). Updates the quality counters of the articles used.
   */
  async onOutgoing(
    ticketId: string,
    text: string,
    answeredById: string | null,
    sentAt: Date,
  ): Promise<'UNCHANGED' | 'EDITED' | null> {
    const ticket = await this.prisma.ticket.findUnique({
      where: { id: ticketId },
      select: { clientGroupId: true },
    });
    if (!ticket) return null;
    const drafts = await this.prisma.aiDraft.findMany({
      where: {
        clientGroupId: ticket.clientGroupId,
        outcome: null,
        text: { not: null },
        createdAt: { gte: new Date(sentAt.getTime() - MAX_AGE_MS), lte: new Date(sentAt.getTime() + 5_000) },
      },
      orderBy: { createdAt: 'desc' },
    });
    for (const d of drafts) {
      if (d.userId && answeredById && d.userId !== answeredById) continue; // a draft made for somebody else
      const outcome = draftOutcome(d.text!, text);
      if (!outcome) continue;
      // claim atomically: two outgoing messages must not both resolve the same draft
      const claimed = await this.prisma.aiDraft.updateMany({
        where: { id: d.id, outcome: null },
        data: { outcome, resolvedAt: new Date() },
      });
      if (claimed.count !== 1) continue;
      const arts = ((d.sources ?? []) as unknown as DraftSource[])
        .filter((s) => s.type === 'article')
        .map((s) => s.id);
      if (arts.length) {
        await this.prisma.kbArticle.updateMany({
          where: { id: { in: arts } },
          data:
            outcome === 'UNCHANGED' ? { sentUnchanged: { increment: 1 } } : { sentEdited: { increment: 1 } },
        });
      }
      return outcome;
    }
    return null;
  }

  /** The extension reports that the human threw the draft away. */
  async discard(id: string): Promise<void> {
    const r = await this.prisma.aiDraft.updateMany({
      where: { id, outcome: null },
      data: { outcome: 'DISCARDED', resolvedAt: new Date() },
    });
    if (r.count === 0 && !(await this.prisma.aiDraft.findUnique({ where: { id } })))
      throw new AppError(HttpStatus.NOT_FOUND, 'NOT_FOUND', 'Qoralama topilmadi');
  }

  async get(id: string) {
    const d = await this.prisma.aiDraft.findUnique({ where: { id } });
    if (!d) throw new AppError(HttpStatus.NOT_FOUND, 'NOT_FOUND', 'Qoralama topilmadi');
    return { ...d, sourceMessageId: d.sourceMessageId?.toString() ?? null };
  }
}
